/**
 * Derives a complete product draft from a product name and category.
 */
export function deriveProductAutoFill(
  input: {
    productName: string;
    categoryId?: string;
    categoryName?: string;
    productType?: string;
    quantityOrWeight?: string;
    price?: number;
    compareAtPrice?: number;
    sku?: string;
    images?: string[];
  },
  categories: Category[] = [],
  allProducts: Product[] = [],
  allGuides: ProductGuide[] = []
): AutoGeneratedProductDraft {
  const name = input.productName.trim();
  const rawSlug = sanitizeSlug(name);
  const detectedEntity = detectProductEntity({ name, slug: rawSlug });
  const entityId = detectedEntity?.id || 'UNKNOWN';

  // Match category
  let categoryId = input.categoryId || '';
  let categoryName = input.categoryName || '';

  if (!categoryId && categories.length > 0) {
    if (detectedEntity) {
      const match = categories.find((c) =>
        c.slug === detectedEntity.categorySlug ||
        c.name.toLowerCase().includes(detectedEntity.canonicalName.toLowerCase()) ||
        (detectedEntity.primaryScope === 'HAIR' && c.name.toLowerCase().includes('hair')) ||
        (detectedEntity.primaryScope === 'SKIN' && (c.name.toLowerCase().includes('face') || c.name.toLowerCase().includes('skin'))) ||
        (detectedEntity.id === 'HENNA_MEHNDI' && c.name.toLowerCase().includes('henna'))
      );
      if (match) {
        categoryId = match.id;
        categoryName = match.name;
      }
    }
    if (!categoryId) {
      categoryId = categories[0].id;
      categoryName = categories[0].name;
    }
  }

  // Determine botanical content based on entity
  const botanicalData = getBotanicalProductContent(name, detectedEntity);

  const productType = input.productType || botanicalData.productType;
  const quantityOrWeight = input.quantityOrWeight || botanicalData.defaultWeight;

  // Build Auto-SEO
  const seoData = deriveProductAutoSeo({
    name,
    slug: rawSlug,
    categoryName,
    shortDescription: botanicalData.shortDescription,
    ingredients: botanicalData.ingredients,
    benefits: botanicalData.benefits,
    price: input.price || 199,
  });

  // Find related products
  const relatedProducts = allProducts
    .filter((p) => {
      if (p.slug === rawSlug || p.isActive === false) return false;
      const otherEntity = detectProductEntity(p);
      if (!otherEntity || !detectedEntity) return false;
      if (otherEntity.id === detectedEntity.id) return true;
      if (detectedEntity.primaryScope === 'HAIR' && otherEntity.primaryScope === 'HAIR') return true;
      if (detectedEntity.primaryScope === 'BODY_ART' && otherEntity.id === 'HENNA_MEHNDI') return true;
      if (detectedEntity.primaryScope === 'SKIN' && otherEntity.primaryScope === 'SKIN') return true;
      return false;
    })
    .slice(0, 4);

  const relatedProductIds = relatedProducts.map((p) => p.id);

  // Match existing guide
  const matchingGuide = allGuides.find((g) =>
    g.slug.includes(rawSlug) ||
    (detectedEntity && g.title.toLowerCase().includes(detectedEntity.canonicalName.toLowerCase())) ||
    (detectedEntity?.id === 'HENNA_MEHNDI' && (g.title.toLowerCase().includes('henna') || g.title.toLowerCase().includes('mehndi')))
  );

  // Missing fields & Checklist evaluation
  const missingFields: string[] = [];
  if (!input.price || input.price <= 0) missingFields.push('price');
  if (!input.sku || input.sku === 'MD-888') missingFields.push('sku');
  if (!input.images || input.images.length === 0 || input.images[0].includes('fallback')) missingFields.push('image');
  if (botanicalData.needsReview) missingFields.push('botanical_review');

  const fullDescription = `${botanicalData.overview}\n\n${botanicalData.whatIsThis}`;

  const draft: AutoGeneratedProductDraft = {
    name,
    slug: rawSlug,
    categoryId,
    categoryName,
    productType,
    quantityOrWeight,
    shortDescription: botanicalData.shortDescription,
    fullDescription,
    overview: botanicalData.overview,
    whatIsThis: botanicalData.whatIsThis,
    ingredients: botanicalData.ingredients,
    benefits: botanicalData.benefits,
    usageInstructions: botanicalData.usageInstructions,
    storageInstructions: botanicalData.storageInstructions,
    importantNotes: botanicalData.importantNotes,
    suitableFor: botanicalData.suitableFor,
    precautions: botanicalData.precautions,
    faqs: botanicalData.faqs,
    tags: [detectedEntity?.canonicalName || 'Botanical', categoryName, 'Natural Herbal', 'Sojat Rajasthan'].filter(Boolean),
    seoTitle: seoData.seoTitle,
    seoDescription: seoData.metaDescription,
    seoKeywords: [seoData.primaryKeyword, ...seoData.secondaryKeywords],
    primaryKeyword: seoData.primaryKeyword,
    secondaryKeywords: seoData.secondaryKeywords,
    longTailKeywords: seoData.longTailKeywords,
    searchAliases: detectedEntity?.aliases || [name.toLowerCase()],
    entityId,
    scientificName: detectedEntity?.scientificName || '',
    isWholesaleEligible: true,
    stockStatus: 'in_stock',
    robotsIndex: true,
    robotsFollow: true,
    relatedProductIds,
    suggestedGuideSlug: matchingGuide?.slug || `${rawSlug}-guide`,
    suggestedGuideTitle: matchingGuide?.title || `Complete Guide to ${name}`,
    schemaType: 'Product',
    checklist: {
      productData: botanicalData.needsReview ? 'NEEDS_REVIEW' : 'READY',
      seo: 'READY',
      search: 'READY',
      schema: 'READY',
      relatedContent: 'READY',
      guideLink: 'READY',
      sitemap: 'READY',
      price: input.price && input.price > 0 ? 'READY' : 'NEEDS_INPUT',
      sku: input.sku && input.sku !== 'MD-888' ? 'READY' : 'NEEDS_INPUT',
      image: input.images && input.images.length > 0 && !input.images[0].includes('fallback') ? 'READY' : 'NEEDS_INPUT',
    },
    needsReview: botanicalData.needsReview || missingFields.length > 0,
    missingFields,
  };

  return draft;
}

